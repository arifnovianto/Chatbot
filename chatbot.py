"""Preprocessing teks"""

stop_words = set(stopwords.words('indonesian'))

def preprocessing(text):

    text = text.lower()

    text = re.sub(r'[^a-zA-Z0-9\s]', '', text)

    words = text.split()

    words = [
        word for word in words
        if word not in stop_words
    ]

    return " ".join(words)


df["pertanyaan_bersih"] = df["pertanyaan"].apply(preprocessing)

